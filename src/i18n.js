export function translate(language, key, replacements = {}) {
  const message = messages[language]?.[key] ?? messages.en[key] ?? key
  return Object.entries(replacements).reduce(
    (result, [name, value]) => result.replaceAll(`{${name}}`, value),
    message,
  )
}
